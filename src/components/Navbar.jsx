            {navLinks.map((link) => (
              <a
                key={link.name}
                href={link.href}
                onClick={() => setIsOpen(false)}
                className="text-phosphor/80 hover:text-target block px-3 py-2 rounded-none text-base font-medium font-mono"
              >
                {link.name}
              </a>
            ))}
